// Packs the built UI (dist/) into server/embedded.ts so `bun build --compile` produces one self-contained binary.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { extname, join, relative } from "node:path";

const DIST = join(import.meta.dir, "../dist");
const OUT = join(import.meta.dir, "../server/embedded.ts");
const MIME: Record<string, string> = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".woff2": "font/woff2",
  ".woff": "font/woff",
  ".json": "application/json",
  ".ico": "image/x-icon",
};

function walk(dir: string, out: string[] = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

const files = walk(DIST);
let total = 0;
const entries = files.map((f) => {
  const key = "/" + relative(DIST, f).split("\\").join("/");
  const data = readFileSync(f).toString("base64");
  total += data.length;
  return `  ${JSON.stringify(key)}: { type: ${JSON.stringify(MIME[extname(f)] ?? "application/octet-stream")}, data: ${JSON.stringify(data)} },`;
});
writeFileSync(
  OUT,
  `// Generated by scripts/embed.ts from dist/. Do not edit.\nexport const assets: Record<string, { type: string; data: string }> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`embedded ${files.length} files (${(total / 1024 / 1024).toFixed(1)} MB base64) into server/embedded.ts`);
